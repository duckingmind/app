import assert from 'node:assert/strict'
import test from 'node:test'
import type { Work } from '../src/core.ts'
import { downloadableImageCount, workRecovery } from '../src/workRecovery.ts'

function work(overrides: Partial<Work> = {}): Work {
  return { id: 'work-1', batch: 'batch-1', kind: 'product', title: '主图', scene: '', pose: '', ratio: '1:1', model: 'image-model', createdAt: '2026-09-20T00:00:00Z', status: 'failed', images: [], ...overrides }
}

test('unknown task outcomes never permit a second generation even when a request remains', () => {
  assert.equal(workRecovery(work({ status: 'paused', taskId: 'task-1' }), true).action, 'query')
  const missingTask = workRecovery(work({ status: 'paused' }), true)
  assert.equal(missingTask.action, 'details')
  assert.match(missingTask.hint, /避免重复提交/)
})

test('known failures need an available original request before showing single-item retry', () => {
  for (const status of ['failed', 'skipped'] as const) {
    assert.equal(workRecovery(work({ status }), false).action, 'configure')
    assert.doesNotMatch(workRecovery(work({ status }), false).hint, /素材未保留|素材已丢失/)
    assert.equal(workRecovery(work({ status }), true).action, 'retry')
  }
  assert.equal(workRecovery(work({ status: 'failed' }), true).label, '重试这一项')
  assert.equal(workRecovery(work({ status: 'skipped' }), true).label, '生成这一项')
})

test('active jobs and existing results cannot be regenerated by recovery controls', () => {
  for (const status of ['queued', 'running'] as const) assert.equal(workRecovery(work({ status }), true).action, 'wait')
  assert.equal(workRecovery(work({ images: [{ url: 'https://example.test/result.png' }] }), true).action, 'details')
  assert.equal(workRecovery(work({ status: 'completed' }), true).action, 'details')
})

test('download count matches actual image files rather than work or task count', () => {
  const works = [work(), work({ images: [{ url: 'one.png' }, { url: 'two.png' }] }), work({ text: 'copy' })]
  assert.equal(downloadableImageCount(works), 2)
  assert.equal(downloadableImageCount([]), 0)
})
